  /// Translate a key, with intelligent fallback to English or Arabic dictionary
  String tr(String key) {
    final code = locale.languageCode;
    if (_localizedValues.containsKey(code) &&
        _localizedValues[code]!.containsKey(key)) {
      return _localizedValues[code]![key]!;
    }
    if (code != 'ar' &&
        _localizedValues['en'] != null &&
        _localizedValues['en']!.containsKey(key)) {
      return _localizedValues['en']![key]!;
    }
    if (_localizedValues['ar']!.containsKey(key)) {
      return _localizedValues['ar']![key]!;
    }
    return key;
  }

  /// Helper for quick bilingual inline text when full key isn't required
  String trBi(String arText, String nonArText) {
    return isArabic ? arText : nonArText;
  }

  /// Helper getter for prayer names
  String getPrayerName(String prayerKey) {
    final normalized = prayerKey.trim().toLowerCase();
    switch (normalized) {
      case 'fajr':
      case 'الفجر':
        return tr('prayer_fajr');
      case 'sunrise':
      case 'الشروق':
        return tr('prayer_sunrise');
      case 'dhuhr':
      case 'الظهر':
        return tr('prayer_dhuhr');
      case 'asr':
      case 'العصر':
        return tr('prayer_asr');
      case 'maghrib':
      case 'المغرب':
        return tr('prayer_maghrib');
      case 'isha':
      case 'العشاء':
        return tr('prayer_isha');
      case 'qiyam':
      case 'قيام الليل':
        return tr('prayer_qiyam');
      default:
        return prayerKey;
    }
  }
