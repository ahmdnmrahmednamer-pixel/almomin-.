  Future<void> init({bool forceReload = false}) async {
    if (_isInitialized && !forceReload) return;
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getStringList('riyad_bookmarks_v1') ?? [];
    _bookmarkedIds
      ..clear()
      ..addAll(saved);
    _isInitialized = true;
    notifyListeners();
  }

  bool isBookmarked(String id) => _bookmarkedIds.contains(id);

  Future<bool> toggleBookmark(String id) async {
    final added = !_bookmarkedIds.contains(id);
    if (added) {
      _bookmarkedIds.add(id);
    } else {
      _bookmarkedIds.remove(id);
    }
    final prefs = await SharedPreferences.getInstance();
    await prefs.setStringList('riyad_bookmarks_v1', _bookmarkedIds.toList());
    notifyListeners();
    return added;
  }

  List<RiyadEntry> getEntriesForEncyclopedia(String encyclopediaId, {int? bookNumber, String query = ''}) {
    final q = query.trim();
    return allEntries.where((e) {
      if (e.encyclopediaId != encyclopediaId) return false;
      if (bookNumber != null && bookNumber > 0 && e.bookNumber != bookNumber) return false;
      if (q.isNotEmpty) {
        final normQ = ArabicNormalizer.normalize(q, loose: true);
        return e.bookTitle.contains(q) ||
            ArabicNormalizer.normalize(e.bookTitle, loose: true).contains(normQ) ||
            e.chapterTitle.contains(q) ||
            ArabicNormalizer.normalize(e.chapterTitle, loose: true).contains(normQ) ||
            e.arabicMatn.contains(q) ||
            ArabicNormalizer.normalize(e.arabicMatn, loose: true).contains(normQ) ||
            e.sharhAndBenefits.contains(q) ||
            ArabicNormalizer.normalize(e.sharhAndBenefits, loose: true).contains(normQ) ||
            e.narrator.contains(q) ||
            ArabicNormalizer.normalize(e.narrator, loose: true).contains(normQ);
      }
      return true;
    }).toList();
  }

  List<MapEntry<int, String>> getBooksForEncyclopedia(String encyclopediaId) {
    final Map<int, String> map = {};
    for (final e in allEntries) {
      if (e.encyclopediaId == encyclopediaId) {
        map.putIfAbsent(e.bookNumber, () => e.bookTitle);
      }
    }
    final list = map.entries.toList()..sort((a, b) => a.key.compareTo(b.key));
    return list;
  }
