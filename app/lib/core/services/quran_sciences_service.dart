  List<QuranScienceEntry> searchEntries(String query, {String category = 'الكل'}) {
    final normQuery = ArabicNormalizer.normalize(query.trim());
    return entries.where((item) {
      if (category != 'الكل' && item.category != category) return false;
      if (normQuery.isEmpty) return true;
      final hay = ArabicNormalizer.normalize(
        '${item.title} ${item.surahName} ${item.category} ${item.narrationOrRule} ${item.practicalBenefit}',
      );
      return hay.contains(normQuery);
    }).toList();
  }
