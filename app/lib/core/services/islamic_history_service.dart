  List<IslamicHistoryEntry> searchEntries(String query, {String category = 'الكل'}) {
    final norm = ArabicNormalizer.normalize(query.trim());
    return entries.where((item) {
      if (category != 'الكل' && item.eraOrCategory != category) return false;
      if (norm.isEmpty) return true;
      final hay = ArabicNormalizer.normalize(
        '${item.title} ${item.eraOrCategory} ${item.summary} ${item.keyHighlights.join(" ")} ${item.lessonLearned}',
      );
      return hay.contains(norm);
    }).toList();
  }
