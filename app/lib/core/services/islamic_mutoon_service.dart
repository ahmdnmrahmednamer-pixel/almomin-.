  Future<void> init({bool forceReload = false}) async {
    if (_isInitialized && !forceReload) return;
    final prefs = await SharedPreferences.getInstance();
    final list = prefs.getStringList(_memorizedKey) ?? [];
    _memorizedIds
      ..clear()
      ..addAll(list);
    _isInitialized = true;
    notifyListeners();
  }

  bool isMemorized(String id) => _memorizedIds.contains(id);

  Future<bool> toggleMemorized(String id) async {
    final added = !_memorizedIds.contains(id);
    if (added) {
      _memorizedIds.add(id);
    } else {
      _memorizedIds.remove(id);
    }
    final prefs = await SharedPreferences.getInstance();
    await prefs.setStringList(_memorizedKey, _memorizedIds.toList());
    notifyListeners();
    return added;
  }

