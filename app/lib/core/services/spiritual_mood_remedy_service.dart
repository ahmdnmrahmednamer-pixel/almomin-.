          'اللَّهُمَّ مَا أَصْبَحَ بِي مِنْ نِعْمَةٍ فَمِنْكَ وَحْدَكَ لَا شَرِيكَ لَكَ، فَلَكَ الْحَمْدُ وَلَكَ الشُّكْرُ',
      recommendedDhikrCount: 3,
    ),
  ];

  String _selectedMoodId = 'anxiety_worry';
  int _activeDhikrProgress = 0;

  String get selectedMoodId => _selectedMoodId;
  int get activeDhikrProgress => _activeDhikrProgress;

  SpiritualMoodRemedy get currentRemedy => allRemedies.firstWhere(
        (r) => r.id == _selectedMoodId,
        orElse: () => allRemedies.first,
      );

  void selectMood(String moodId) {
    if (allRemedies.any((r) => r.id == moodId)) {
      _selectedMoodId = moodId;
      _activeDhikrProgress = 0;
      notifyListeners();
    }
  }

  void incrementDhikr() {
    if (_activeDhikrProgress < currentRemedy.recommendedDhikrCount) {
      _activeDhikrProgress++;
      notifyListeners();
    }
  }

  void resetDhikr() {
    _activeDhikrProgress = 0;
    notifyListeners();
  }
}
