  List<FiqhTopicItem> searchTopics(String query, {String category = 'الكل', bool favoritesOnly = false}) {
    final normQuery = ArabicNormalizer.normalize(query.trim());
    return topics.where((item) {
      if (favoritesOnly && !_favoriteIds.contains(item.id)) return false;
      if (category != 'الكل' && item.chapter != category) return false;
      if (normQuery.isEmpty) return true;
      final hay = ArabicNormalizer.normalize(
        '${item.title} ${item.chapter} ${item.summaryRuling} ${item.evidenceText} ${item.contemporaryNote} ${item.madhahibComparison.values.join(" ")}',
      );
      return hay.contains(normQuery);
    }).toList();
  }
