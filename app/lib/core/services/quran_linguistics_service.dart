  /// Syntactic & Morphological Analyzer for any Quranic Word
  static WordGrammar _analyzeSingleWord(String rawWord, int index) {
    final clean = rawWord.replaceAll(RegExp(r'[\u06D6-\u06ED\u06DD\u06DE]'), '').trim();
    final bare = _normalizeToken(clean);

    // Check common particles & pronouns first
    if (bare == 'ان' && clean.contains('إِنَّ')) {
      return WordGrammar(
        word: clean,
        role: 'حرف توكيد ونصب مشبه بالفعل (ينصب الاسم ويرفع الخبر)',
        caseEnding: 'مبني على الفتح لا محل له من الإعراب',
      );
    }
    if (bare == 'الذين' || bare == 'الذي' || bare == 'التي') {
      return WordGrammar(
        word: clean,
        role: 'اسم موصول لربط جملة الصلة بما قبلها',
        caseEnding: 'مبني في محل رفع أو نصب أو جر حسب موقعه في الجملة',
      );
    }
    if (bare == 'ذلك' || bare == 'هذا' || bare == 'هذه' || bare == 'اوليك') {
      return WordGrammar(
        word: clean,
        role: 'اسم إشارة للتعظيم والتنبيه',
        caseEnding: 'مبني في محل رفع مبتدأ أو حسب موقعه الإعرابي',
      );
    }
    if (bare == 'في' || bare == 'من' || bare == 'الي' || bare == 'علي' || bare == 'عن') {
      return WordGrammar(
        word: clean,
        role: 'حرف جر أصلي يربط الأسماء بالأفعال',
        caseEnding: 'مبني لا محل له من الإعراب وما بعده مجرور',
      );
    }
    if (bare == 'لم' || bare == 'لما') {
      return WordGrammar(
        word: clean,
        role: 'حرف نفي وجزم وقلب يختص بالمضارع',
        caseEnding: 'مبني على السكون لا محل له من الإعراب',
      );
    }
    if (bare == 'لن') {
      return WordGrammar(
        word: clean,
        role: 'حرف نفي ونصب واستقبال يختص بالمضارع',
        caseEnding: 'مبني على السكون لا محل له من الإعراب',
      );
    }
    if (bare == 'قد' || bare == 'لقد') {
      return WordGrammar(
        word: clean,
        role: 'حرف تحقيق وتوكيد يدخل على الفعل',
        caseEnding: 'مبني على السكون لا محل له من الإعراب',
      );
    }
    if (bare == 'الله' || bare == 'لله' || bare == 'بالله' || bare == 'والله') {
      final hasJar = bare.startsWith('ل') || bare.startsWith('ب') || bare.startsWith('و');
      return WordGrammar(
        word: clean,
        role: hasJar ? 'جار ومجرور (لفظ الجلالة المعظم)' : 'لفظ الجلالة المعظم (مبتدأ / فاعل / مضاف إليه)',
        caseEnding: clean.endsWith('ُ')
            ? 'مرفوع وعلامة رفعه الضمة الظاهرة للتعظيم'
            : (clean.endsWith('َ') ? 'منصوب على التعظيم بالفتحة الظاهرة' : 'مجرور على التعظيم بالكسرة الظاهرة'),
      );
    }
    if (bare == 'قل' || bare == 'قال' || bare == 'قالوا') {
      return WordGrammar(
        word: clean,
        role: bare == 'قل'
            ? 'فعل أمر مبني على السكون والفاعل ضمير مستتر تقديره أنت'
            : 'فعل ماضٍ والجملة بعده في محل نصب مقول القول',
        caseEnding: bare == 'قالوا' ? 'مبني على الضم لاتصاله بواو الجماعة' : 'مبني على الفتح أو السكون',
      );
    }

    // Inspect ending diacritics and suffixes
    String role;
    String caseEnd;

    if (clean.endsWith('ونَ') || clean.endsWith('ُونَ')) {
      if (bare.startsWith('ي') || bare.startsWith('ت')) {
        role = 'فعل مضارع من الأفعال الخمسة، وواو الجماعة ضمير متصل في محل رفع فاعل';
        caseEnd = 'مرفوع وعلامة رفعه ثبوت النون';
      } else {
        role = 'جمع مذكر سالم (نعت / خبر / فاعل)';
        caseEnd = 'مرفوع وعلامة رفعه الواو نيابة عن الضمة';
      }
    } else if (clean.endsWith('ينَ') || clean.endsWith('ِينَ')) {
      role = 'جمع مذكر سالم في موقع النصب أو الجر (مضاف إليه / نعت / مفعول به)';
      caseEnd = 'منصوب أو مجرور وعلامة إعرابه الياء لأنه جمع مذكر سالم';
    } else if (clean.endsWith('وا') || clean.endsWith('ُوا')) {
      role = 'فعل مسند إلى واو الجماعة، والواو ضمير متصل في محل رفع فاعل والألف فارقة';
      caseEnd = 'مبني على الضم أو حذف النون';
    } else if (clean.endsWith('ٌ') || clean.endsWith('ُ')) {
      role = index == 0 ? 'مبتدأ أو فاعل مرفوع في صدر الجملة القرآنية' : 'خبر أو فاعل أو نعت مرفوع';
      caseEnd = 'مرفوع وعلامة رفعه الضمة الظاهرة على آخره';
    } else if (clean.endsWith('ً') || clean.endsWith('ًا') || clean.endsWith('َ')) {
      role = 'منصوب على المفعولية أو الحالية أو الظرفية أو اسم ناسخ';
      caseEnd = 'منصوب وعلامة نصبه الفتحة الظاهرة على آخره';
    } else if (clean.endsWith('ٍ') || clean.endsWith('ِ')) {
      role = 'اسم مجرور بحرف الجر أو مضاف إليه أو نعت مجرور';
      caseEnd = 'مجرور وعلامة جره الكسرة الظاهرة تحت آخره';
    } else {
      role = 'ركن إسنادي أو فضلة في سياق النظم القرآني المحكم';
      caseEnd = 'معرب أو مبني بحسب موقعه التركيبي في الآية';
    }

    return WordGrammar(word: clean, role: role, caseEnding: caseEnd);
  }

  /// Resolves the grammatical breakdown (I'rab) and rhetorical beauty
  static AyahGrammar _resolveGrammar(int surahId, int ayahNumber, String text, String surahName) {
    final rawWords = text
        .split(RegExp(r'\s+'))
        .where((w) => w.trim().isNotEmpty && !RegExp(r'^[\u06D6-\u06ED]+$').hasMatch(w.trim()))
        .take(12)
        .toList();

    final List<WordGrammar> words = [];
    for (int i = 0; i < rawWords.length; i++) {
      words.add(_analyzeSingleWord(rawWords[i], i));
    }

    final key = '$surahId:$ayahNumber';
    String summary;
    if (_curatedIrabSummaries.containsKey(key)) {
      summary = _curatedIrabSummaries[key]!;
    } else if (words.isNotEmpty) {
      final preview = words.take(4).map((w) => '﴿${w.word}﴾: ${w.role} (${w.caseEnding})').join(' · ');
      summary = 'الإعراب التحليلي للآية ($ayahNumber) من سورة $surahName:\n$preview.';
    } else {
      summary = 'الجملة القرآنية الكريمة منتظمة على أرفع أساليب الإسناد العربي الفصيح بين المسند والمسند إليه ومتعلقاتهما.';
    }

    final rhetoric = 'من لطائف البيان والبلاغة في الآية ($ayahNumber) من سورة $surahName: '
        'تآلف الألفاظ مع المعاني في إيجاز محكم، وتناسب فواصل الآية مع جوّ السورة ومقاصدها التشريعية والتربوية، مما يورث القلب خشوعاً واللسان بياناً.';

    return AyahGrammar(
      surahId: surahId,
      ayahNumber: ayahNumber,
      summary: summary,
      rhetoricSummary: rhetoric,
      words: words,
    );
  }
