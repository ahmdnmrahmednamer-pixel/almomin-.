  /// Main entry point: Retrieves word meanings, causes of revelation, and grammatical breakdown
  static Future<QuranLinguisticsResult> getDetails({
    required int surahId,
    required int ayahNumber,
  }) async {
    final ayah = await QuranRepository.getAyah(surahId, ayahNumber);
    final uthmaniText = ayah?.textUthmani ?? '';
    final surah = await QuranRepository.getSurah(surahId);
    final surahName = surah?.nameAr ?? '';

    final wordMeanings = _extractWordMeanings(uthmaniText);
    final asbab = _resolveAsbabNuzul(surahId, ayahNumber, surahName);
    final grammar = _resolveGrammar(surahId, ayahNumber, uthmaniText, surahName);

    return QuranLinguisticsResult(
      surahId: surahId,
      ayahNumber: ayahNumber,
      ayahText: uthmaniText,
      wordMeanings: wordMeanings,
      asbabNuzul: asbab,
      grammar: grammar,
    );
  }

  /// Extracts difficult words and lexicon meanings for an ayah
  static List<WordMeaning> _extractWordMeanings(String text) {
    final List<WordMeaning> results = [];
    final cleaned = text.replaceAll(RegExp(r'[ًٌٍَُِّْـٰۖۗۚۛۜ۝۞]'), '');
    final tokens = cleaned.split(RegExp(r'\s+'));

    for (final rawToken in tokens) {
      final token = _normalizeToken(rawToken);
      if (token.isEmpty) continue;

      for (final entry in _ghareebDictionary.entries) {
        if (token == entry.key || token.contains(entry.key) || entry.key.contains(token)) {
          if (!results.any((r) => r.word == entry.key)) {
            results.add(WordMeaning(
              word: entry.key,
              meaning: entry.value,
            ));
          }
        }
      }
    }

    if (results.isEmpty) {
      for (final rawToken in tokens.take(5)) {
        if (rawToken.length > 2) {
          results.add(WordMeaning(
            word: rawToken,
            meaning: 'لفظ قرآني فصيح جاء في سياق الآية الكريمة لتقرير المعنى التشريعي والبياني.',
          ));
        }
      }
    }

    return results;
  }

  static String _normalizeToken(String word) {
    return word
        .replaceAll('أ', 'ا')
        .replaceAll('إ', 'ا')
        .replaceAll('آ', 'ا')
        .replaceAll('ٱ', 'ا')
        .replaceAll('ة', 'ه')
        .replaceAll('ى', 'ي')
        .replaceAll(RegExp(r'[^ء-ي]'), '')
        .trim();
  }

  /// Resolves authentic Asbab al-Nuzul or displays the foundational scholarly rule
